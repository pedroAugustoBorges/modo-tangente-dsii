CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'STUDENT'
        CHECK (role IN ('STUDENT', 'ADMIN')),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX ux_app_users_email_ci ON app_users (lower(email));

CREATE TABLE topics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(160) NOT NULL,
    description TEXT,
    display_order INTEGER NOT NULL DEFAULT 0 CHECK (display_order >= 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_topics_active_order ON topics (active, display_order, id);

CREATE TABLE quizzes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id BIGINT NOT NULL REFERENCES topics(id) ON DELETE RESTRICT,
    title VARCHAR(180) NOT NULL,
    description TEXT,
    instructions TEXT,
    display_order INTEGER NOT NULL DEFAULT 0 CHECK (display_order >= 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (id, topic_id)
);
CREATE INDEX ix_quizzes_topic_order ON quizzes (topic_id, active, display_order, id);

CREATE TABLE quiz_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id BIGINT NOT NULL REFERENCES quizzes(id) ON DELETE RESTRICT,
    position INTEGER NOT NULL CHECK (position > 0),
    statement TEXT NOT NULL,
    study_guidance TEXT,
    points NUMERIC(7,2) NOT NULL DEFAULT 1 CHECK (points >= 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (quiz_id, position),
    UNIQUE (id, quiz_id)
);
CREATE INDEX ix_questions_quiz_position ON quiz_questions (quiz_id, active, position);

CREATE TABLE question_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL REFERENCES quiz_questions(id) ON DELETE RESTRICT,
    position INTEGER NOT NULL CHECK (position > 0),
    option_text TEXT NOT NULL,
    is_correct BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (question_id, position),
    UNIQUE (id, question_id)
);
CREATE UNIQUE INDEX ux_question_one_correct_option
    ON question_options (question_id) WHERE is_correct = TRUE;

CREATE TABLE quiz_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE RESTRICT,
    quiz_id BIGINT NOT NULL REFERENCES quizzes(id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS'
        CHECK (status IN ('IN_PROGRESS', 'COMPLETED', 'ABANDONED')),
    score NUMERIC(9,2) CHECK (score IS NULL OR score >= 0),
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    finished_at TIMESTAMPTZ,
    UNIQUE (id, quiz_id),
    CHECK (finished_at IS NULL OR finished_at >= started_at),
    CHECK (
        (status = 'IN_PROGRESS' AND finished_at IS NULL)
        OR (status IN ('COMPLETED', 'ABANDONED') AND finished_at IS NOT NULL)
    )
);
CREATE INDEX ix_attempts_user_started ON quiz_attempts (user_id, started_at DESC);

CREATE TABLE question_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_attempt_id BIGINT NOT NULL,
    quiz_id BIGINT NOT NULL,
    question_id BIGINT NOT NULL,
    selected_option_id BIGINT,
    is_correct BOOLEAN,
    answered_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (quiz_attempt_id, question_id),
    UNIQUE (id, question_id),
    FOREIGN KEY (quiz_attempt_id, quiz_id)
        REFERENCES quiz_attempts(id, quiz_id) ON DELETE RESTRICT,
    FOREIGN KEY (question_id, quiz_id)
        REFERENCES quiz_questions(id, quiz_id) ON DELETE RESTRICT,
    FOREIGN KEY (selected_option_id, question_id)
        REFERENCES question_options(id, question_id) ON DELETE RESTRICT,
    CHECK (
        (selected_option_id IS NULL AND is_correct IS NULL AND answered_at IS NULL)
        OR (selected_option_id IS NOT NULL AND is_correct IS NOT NULL AND answered_at IS NOT NULL)
    )
);
    -- A constraint UNIQUE (quiz_attempt_id, question_id) ja cobre a consulta por quiz_attempt_id.
    -- Nao criar indice redundante com o mesmo prefixo.

CREATE TABLE conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_attempt_id BIGINT NOT NULL UNIQUE
        REFERENCES question_attempts(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE RESTRICT,
    sender_role VARCHAR(20) NOT NULL CHECK (sender_role IN ('STUDENT', 'TUTOR')),
    content TEXT NOT NULL CHECK (length(trim(content)) > 0),
    request_id UUID,
    reply_to_message_id BIGINT,
    llm_status VARCHAR(20),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (conversation_id, request_id),
    UNIQUE (id, conversation_id),
    UNIQUE (reply_to_message_id),
    FOREIGN KEY (reply_to_message_id, conversation_id)
        REFERENCES messages(id, conversation_id) ON DELETE RESTRICT,
    CHECK (
        (sender_role = 'STUDENT' AND request_id IS NOT NULL AND reply_to_message_id IS NULL
            AND llm_status IS NOT NULL
            AND llm_status IN ('PROCESSING', 'COMPLETED', 'FAILED'))
        OR (sender_role = 'TUTOR' AND request_id IS NULL AND reply_to_message_id IS NOT NULL
            AND llm_status IS NULL)
    )
);
CREATE INDEX ix_messages_conversation_order
    ON messages (conversation_id, created_at, id);

